create or replace function public.bootstrap_admin(p_email text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (select 1 from public.profiles where role = 'admin') then
    raise exception 'Admin sudah ada. Hanya satu admin yang diizinkan.';
  end if;

  if not exists (
    select 1 from public.profiles where lower(email) = lower(trim(p_email))
  ) then
    raise exception 'Akun dengan email tersebut belum terdaftar.';
  end if;

  perform set_config('catatkas.allow_profile_security_change', 'on', true);

  update public.profiles
  set role = 'admin'
  where lower(email) = lower(trim(p_email))
    and role = 'user';
end;
$$;

create or replace function public.admin_dashboard_stats()
returns table (
  total_users bigint,
  suspended_users bigint,
  total_transactions bigint,
  total_income numeric,
  total_expense numeric,
  active_ads bigint
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Akses ditolak.';
  end if;

  return query
  select
    (select count(*) from public.profiles)::bigint,
    (select count(*) from public.profiles where is_suspended)::bigint,
    (select count(*) from public.transactions)::bigint,
    (select coalesce(sum(amount), 0) from public.transactions where type = 'income')::numeric,
    (select coalesce(sum(amount), 0) from public.transactions where type = 'expense')::numeric,
    (select count(*) from public.ads where is_active)::bigint;
end;
$$;

