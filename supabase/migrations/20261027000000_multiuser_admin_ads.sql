    raise exception 'Akses ditolak.';
  end if;

  delete from public.transactions where user_id = v_user_id;
  delete from public.transfers where user_id = v_user_id;
  delete from public.budgets where user_id = v_user_id;
  delete from public.categories where user_id = v_user_id;
  delete from public.accounts where user_id = v_user_id;
  delete from public.settings where user_id = v_user_id;

  perform public.seed_user_defaults(v_user_id);
end;
$$;

create or replace function public.replace_my_data(payload jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_row jsonb;
  v_old_id bigint;
  v_new_id bigint;
  v_category_id bigint;
  v_account_id bigint;
  v_from_id bigint;
  v_to_id bigint;
  v_key text;
  v_value jsonb;
  v_time time;
  v_date date;
begin
  if v_user_id is null or not public.is_active_user() then
    raise exception 'Akses ditolak.';
  end if;
  if payload is null or jsonb_typeof(payload) <> 'object' then
    raise exception 'Data backup tidak valid.';
  end if;

  create temp table _cat_map (old_id bigint primary key, new_id bigint not null) on commit drop;
  create temp table _acct_map (old_id bigint primary key, new_id bigint not null) on commit drop;

  delete from public.transactions where user_id = v_user_id;
  delete from public.transfers where user_id = v_user_id;
  delete from public.budgets where user_id = v_user_id;
  delete from public.categories where user_id = v_user_id;
  delete from public.accounts where user_id = v_user_id;
  delete from public.settings where user_id = v_user_id;

  for v_row in
    select value from jsonb_array_elements(coalesce(payload -> 'categories', '[]'::jsonb))
  loop
    v_old_id := nullif(v_row ->> 'id', '')::bigint;
    if v_old_id is null then
      raise exception 'ID kategori pada backup tidak valid.';
    end if;

    insert into public.categories
      (user_id, type, name, icon, color, is_default, sort_order, created_at, updated_at)
    values (
      v_user_id,
      case when v_row ->> 'type' = 'income' then 'income' else 'expense' end,
      coalesce(nullif(v_row ->> 'name', ''), 'Tanpa nama'),
      coalesce(nullif(v_row ->> 'icon', ''), '📦'),
      coalesce(nullif(v_row ->> 'color', ''), '#6366f1'),
      coalesce((v_row ->> 'isDefault')::boolean, false),
      coalesce((v_row ->> 'order')::integer, 0),
      coalesce((v_row ->> 'createdAt')::timestamptz, now()),
      coalesce((v_row ->> 'updatedAt')::timestamptz, now())
    )
    returning id into v_new_id;

    insert into _cat_map (old_id, new_id) values (v_old_id, v_new_id);
  end loop;

  for v_row in
    select value from jsonb_array_elements(coalesce(payload -> 'accounts', '[]'::jsonb))
  loop
    v_old_id := nullif(v_row ->> 'id', '')::bigint;
    if v_old_id is null then
      raise exception 'ID akun pada backup tidak valid.';
    end if;

    insert into public.accounts
      (user_id, name, icon, color, initial_balance, is_default, is_active, sort_order, created_at, updated_at)
    values (
      v_user_id,
      coalesce(nullif(v_row ->> 'name', ''), 'Tanpa nama'),
      coalesce(nullif(v_row ->> 'icon', ''), '💵'),
      coalesce(nullif(v_row ->> 'color', ''), '#6366f1'),
      coalesce((v_row ->> 'initialBalance')::bigint, 0),
      coalesce((v_row ->> 'isDefault')::boolean, false),
      coalesce((v_row ->> 'isActive')::boolean, true),
      coalesce((v_row ->> 'order')::integer, 0),
      coalesce((v_row ->> 'createdAt')::timestamptz, now()),
      coalesce((v_row ->> 'updatedAt')::timestamptz, now())
    )
    returning id into v_new_id;

    insert into _acct_map (old_id, new_id) values (v_old_id, v_new_id);
  end loop;

  for v_row in
    select value from jsonb_array_elements(coalesce(payload -> 'budgets', '[]'::jsonb))
  loop
    select new_id into v_category_id
    from _cat_map
    where old_id = nullif(v_row ->> 'categoryId', '')::bigint;

    if v_category_id is null then
      raise exception 'Kategori budget tidak ditemukan pada backup.';
    end if;

    insert into public.budgets
      (user_id, category_id, amount, period, created_at, updated_at)
    values (
      v_user_id,
      v_category_id,
      greatest(coalesce((v_row ->> 'amount')::bigint, 0), 0),
      coalesce(nullif(v_row ->> 'period', ''), to_char(current_date, 'YYYY-MM')),
      coalesce((v_row ->> 'createdAt')::timestamptz, now()),
      coalesce((v_row ->> 'updatedAt')::timestamptz, now())
    );
  end loop;

  for v_row in
    select value from jsonb_array_elements(coalesce(payload -> 'transactions', '[]'::jsonb))
  loop
    select new_id into v_category_id
    from _cat_map
    where old_id = nullif(v_row ->> 'categoryId', '')::bigint;
    select new_id into v_account_id
    from _acct_map
    where old_id = nullif(v_row ->> 'accountId', '')::bigint;

    if v_category_id is null or v_account_id is null then
      raise exception 'Kategori atau akun transaksi tidak ditemukan pada backup.';
    end if;

    v_time := coalesce(nullif(v_row ->> 'time', '')::time, '00:00'::time);
    v_date := coalesce(nullif(v_row ->> 'date', '')::date, current_date);

    insert into public.transactions
      (user_id, type, amount, category_id, account_id, date, time, note, created_at, updated_at)
    values (
      v_user_id,
      case when v_row ->> 'type' = 'income' then 'income' else 'expense' end,
      greatest(coalesce((v_row ->> 'amount')::bigint, 0), 0),
      v_category_id,
      v_account_id,
      v_date,
      v_time,
      coalesce(v_row ->> 'note', ''),
      coalesce((v_row ->> 'createdAt')::timestamptz, now()),
      coalesce((v_row ->> 'updatedAt')::timestamptz, now())
    );
  end loop;

  for v_row in
    select value from jsonb_array_elements(coalesce(payload -> 'transfers', '[]'::jsonb))
  loop
    select new_id into v_from_id
    from _acct_map
    where old_id = nullif(v_row ->> 'fromAccountId', '')::bigint;
    select new_id into v_to_id
    from _acct_map
    where old_id = nullif(v_row ->> 'toAccountId', '')::bigint;

    if v_from_id is null or v_to_id is null or v_from_id = v_to_id then
      raise exception 'Akun transfer tidak valid pada backup.';
    end if;

    v_time := coalesce(nullif(v_row ->> 'time', '')::time, '00:00'::time);
    v_date := coalesce(nullif(v_row ->> 'date', '')::date, current_date);

    insert into public.transfers
      (user_id, from_account_id, to_account_id, amount, date, time, note, created_at, updated_at)
    values (
      v_user_id,
      v_from_id,
      v_to_id,
      greatest(coalesce((v_row ->> 'amount')::bigint, 0), 1),
      v_date,
      v_time,
      coalesce(v_row ->> 'note', ''),
      coalesce((v_row ->> 'createdAt')::timestamptz, now()),
      coalesce((v_row ->> 'updatedAt')::timestamptz, now())
    );
  end loop;

  for v_key, v_value in
    select key, value from jsonb_each(coalesce(payload -> 'settings', '{}'::jsonb))
  loop
    if v_key = 'defaultAccountId' and v_value <> 'null'::jsonb then
      select new_id into v_account_id
      from _acct_map
      where old_id = (v_value #>> '{}')::bigint;
      v_value := coalesce(to_jsonb(v_account_id), 'null'::jsonb);
    end if;

    insert into public.settings (user_id, key, value)
    values (v_user_id, v_key, v_value)
    on conflict (user_id, key) do update set value = excluded.value;
  end loop;

  insert into public.settings (user_id, key, value)
  values (v_user_id, 'isFirstLaunch', 'false'::jsonb)
  on conflict (user_id, key) do update set value = 'false'::jsonb;
end;
$$;

