create or replace function public.create_public_ad_order(
  p_ad_id bigint,
  p_package_id bigint,
  p_contact_name text,
  p_contact_email text,
  p_contact_phone text,
  p_payment_method text,
  p_terms_accepted boolean
)
returns table (
  id bigint,
  order_code text,
  public_token uuid,
  total_amount bigint,
  expires_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ad public.ads%rowtype;
  v_package public.ad_packages%rowtype;
  v_settings public.ad_payment_settings%rowtype;
  v_code integer;
  v_order_code text;
  v_total bigint;
  v_email text;
  v_attempt integer;
begin
  if coalesce(p_terms_accepted, false) is not true then
    raise exception 'Ketentuan iklan harus disetujui.';
  end if;

  v_email := lower(trim(coalesce(p_contact_email, '')));
  if v_email = '' or v_email !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'Email pengiklan tidak valid.';
  end if;
  if length(trim(coalesce(p_contact_name, ''))) < 2 then
    raise exception 'Nama pengiklan tidak valid.';
  end if;

  select * into v_package
  from public.ad_packages
  where id = p_package_id
    and is_active;

  if not found then
    raise exception 'Paket iklan tidak tersedia.';
  end if;

  select * into v_settings
  from public.ad_payment_settings
  where id = 1;

  if not found or not v_settings.accepting_orders then
    raise exception 'Pemesanan iklan sedang ditutup.';
  end if;
  if p_payment_method = 'qris' and coalesce(v_settings.qris_image_path, '') = '' then
    raise exception 'QRIS belum tersedia.';
  end if;
  if p_payment_method = 'bank_transfer' and trim(v_settings.account_number) = '' then
    raise exception 'Rekening pembayaran belum tersedia.';
  end if;

  select * into v_ad
  from public.ads
  where id = p_ad_id
    and source = 'public'
    and package_id = p_package_id
    and is_active = false
  for update;

  if not found then
    raise exception 'Data iklan tidak ditemukan.';
  end if;

  if exists (
    select 1
    from public.ad_orders
    where ad_id = v_ad.id
      and status in ('awaiting_payment', 'awaiting_review', 'approved')
  ) then
    raise exception 'Iklan ini sudah memiliki pesanan aktif.';
  end if;

  update public.ad_orders
  set status = 'expired'
  where status = 'awaiting_payment'
    and expires_at <= now();

  for v_attempt in 1..20 loop
    v_code := 100 + floor(random() * 900)::integer;
    v_total := v_package.price_idr + v_code;
    v_order_code := 'AD-' || to_char(now(), 'YYMMDD') || '-' ||
      upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6));

    begin
      return query
      insert into public.ad_orders (
        order_code,
        ad_id,
        source,
        contact_name,
        contact_email,
        contact_phone,
        package_id,
        package_name,
        placement,
        duration_days,
        priority,
        base_amount,
        unique_code,
        total_amount,
        payment_method,
        status,
        terms_accepted_at,
        expires_at
      )
      values (
        v_order_code,
        v_ad.id,
        'public',
        trim(left(p_contact_name, 100)),
        v_email,
        trim(left(coalesce(p_contact_phone, ''), 40)),
        v_package.id,
        v_package.name,
        v_package.placement,
        v_package.duration_days,
        v_package.priority,
        v_package.price_idr,
        v_code,
        v_total,
        p_payment_method,
        'awaiting_payment',
        now(),
        now() + interval '24 hours'
      )
      returning ad_orders.id, ad_orders.order_code, ad_orders.public_token,
        ad_orders.total_amount, ad_orders.expires_at;

      return;
    exception
      when unique_violation then
        v_order_code := null;
    end;
  end loop;

  raise exception 'Nomor pembayaran unik sedang tidak tersedia. Coba lagi.';
end;
$$;

create or replace function public.submit_public_ad_proof(
  p_token uuid,
  p_proof_path text,
  p_payer_name text,
  p_payer_note text default ''
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.ad_orders%rowtype;
begin
  if p_proof_path is null or p_proof_path not like p_token::text || '/%' then
    raise exception 'Path bukti pembayaran tidak valid.';
  end if;

  select * into v_order
  from public.ad_orders
  where public_token = p_token
  for update;

  if not found then
    raise exception 'Pesanan tidak ditemukan.';
  end if;
  if v_order.status = 'awaiting_payment' and v_order.expires_at <= now() then
    update public.ad_orders
    set status = 'expired'
    where id = v_order.id;
    raise exception 'Pesanan sudah kedaluwarsa.';
  end if;
  if v_order.status not in ('awaiting_payment', 'awaiting_review') then
    raise exception 'Pesanan tidak dapat menerima bukti pembayaran.';
  end if;

  update public.ad_orders
  set status = 'awaiting_review',
      proof_path = p_proof_path,
      payer_name = trim(left(coalesce(p_payer_name, ''), 100)),
      payer_note = trim(left(coalesce(p_payer_note, ''), 500)),
      submitted_at = coalesce(submitted_at, now())
  where id = v_order.id;

  return 'awaiting_review';
end;
$$;

create or replace function public.admin_review_ad_order(
  p_order_id bigint,
  p_action text,
  p_note text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.ad_orders%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Akses admin diperlukan.';
  end if;
  if p_action not in ('approve', 'reject') then
    raise exception 'Aksi review tidak valid.';
  end if;

  select * into v_order
  from public.ad_orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'Pesanan tidak ditemukan.';
  end if;

  if p_action = 'approve' then
    if v_order.status <> 'awaiting_review' then
      raise exception 'Pesanan belum siap diverifikasi.';
    end if;

    update public.ad_orders
    set status = 'approved',
        reviewed_by = auth.uid(),
        reviewed_at = now(),
        review_note = trim(left(coalesce(p_note, ''), 500))
    where id = v_order.id;

    update public.ads
    set is_active = true,
        placement = v_order.placement,
        priority = v_order.priority,
        package_id = v_order.package_id,
        starts_at = now(),
        ends_at = now() + make_interval(days => v_order.duration_days)
    where id = v_order.ad_id;
  else
    if v_order.status not in ('awaiting_payment', 'awaiting_review') then
      raise exception 'Pesanan tidak dapat ditolak pada status ini.';
    end if;

    update public.ad_orders
    set status = 'rejected',
        reviewed_by = auth.uid(),
        reviewed_at = now(),
        review_note = coalesce(nullif(trim(left(coalesce(p_note, ''), 500)), ''), 'Ditolak admin.')
    where id = v_order.id;

    update public.ads
    set is_active = false
    where id = v_order.ad_id;
  end if;

  insert into public.admin_audit_log (actor_id, target_user_id, action, metadata)
  values (
    auth.uid(),
    v_order.advertiser_id,
    case when p_action = 'approve' then 'ad_order_approved' else 'ad_order_rejected' end,
    jsonb_build_object(
      'order_id', v_order.id,
      'order_code', v_order.order_code,
      'total_amount', v_order.total_amount
    )
  );
end;
$$;

