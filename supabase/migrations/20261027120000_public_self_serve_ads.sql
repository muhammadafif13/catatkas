create or replace function public.prevent_ad_delete_with_orders()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (
    select 1
    from public.ad_orders
    where ad_id = old.id
      and status in ('awaiting_payment', 'awaiting_review', 'approved')
  ) then
    raise exception 'Iklan dengan pesanan berjalan atau disetujui tidak dapat dihapus.';
  end if;

  return old;
end;
$$;

